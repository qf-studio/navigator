def judge_fixtures() -> str:
    evals = json.loads((ROOT / "hooks/nav_hook_lib/fixtures/judge_eval.json").read_text())["prompts"]
    recorded = json.loads((ROOT / "hooks/nav_hook_lib/fixtures/judge_eval_recorded.json").read_text())
    settings = judge.settings({})
    thresholds = judge._thresholds(settings)
    cases = []
    for prompt, rec in zip(evals, recorded):
        text = prompt["text"]
        j = judge.parse_response(rec["_doc"], thresholds)
        j.latency_ms = int(rec.get("_latency_ms") or 0)
        cases.append({
            "prompt": text,
            "doc": rec["_doc"],
            "latency_ms": j.latency_ms,
            "request": judge.build_request(text, settings),
            "verdicts": {
                "task": j.task_verdict(), "loop": j.loop_verdict(),
                "complexity": j.complexity_if_confident(), "level": j.complexity_level(),
                "ambiguity": j.ambiguity_if_confident(),
                "dimensions": {d: j.dimension_verdict(d) for d in judge.DIMENSIONS},
            },
            "workflow": scoring.detect_workflow(text, judgment=j),
            "ambiguity": scoring.score_ambiguity(text, judgment=j),
        })
    redact = [{"input": t, "output": judge.redact_secrets(t)} for t in REDACT_CORPUS]
    return HEADER + "\n" + ts_const("JUDGE_CASES", cases, "ReadonlyArray<{ prompt: string; doc: Record<string, unknown>; latency_ms: number; request: unknown; verdicts: unknown; workflow: unknown; ambiguity: unknown }>", compact=True) + "\n" + ts_const("REDACT_CASES", redact)


