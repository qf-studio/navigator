HEADER = "// GENERATED by scripts/gen_mod_data.py from the Python runtime. Do not edit.\n"


def ts_const(name: str, value, type_ann: str = "", compact: bool = False) -> str:
    """`compact` for large fixtures: the mod test kit refuses imports over 1 MiB."""
    body = json.dumps(value, ensure_ascii=False, separators=(",", ":")) if compact \
        else json.dumps(value, indent=2, ensure_ascii=False)
    if type_ann:  # large fixtures: an explicit row type, no `as const` (TS union blow-up)
        return f"export const {name}: {type_ann} = {body}\n"
    return f"export const {name} = {body} as const\n"


def config_defaults() -> str:
    return HEADER + "\n" + ts_const("CONFIG_DEFAULTS", config.DEFAULTS)


def sentinel_data() -> str:
    return (HEADER + "\n" + ts_const("TAGS", sentinels.TAGS)
            + "\n" + ts_const("BUDGETS", budget.BUDGETS)
            + "\n" + ts_const("TRUNCATION_MARKER", budget.TRUNCATION_MARKER))


