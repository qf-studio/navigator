def _test_prompts() -> list:
    """Prompts the Python op/scoring tests already exercise (committed test files only)."""
    found = []
    for path in sorted((ROOT / "hooks").rglob("test_*.py")):
        text = path.read_text(encoding="utf-8")
        found += re.findall(r'ctx\("((?:[^"\\]|\\.){1,200})"', text)
        found += re.findall(r'(?:score_ambiguity|detect_workflow|score)\("((?:[^"\\]|\\.){1,200})"',
                            text)
    return found


def scoring_corpus() -> list:
    evals = json.loads((ROOT / "hooks/nav_hook_lib/fixtures/judge_eval.json").read_text())
