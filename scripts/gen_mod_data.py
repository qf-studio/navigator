def op_fixtures(only: str) -> str:
    """Python op results for prompt_gate / prompt_brief, judge off, no graph (recall '').

    One file per config variant: the mod test kit refuses imports over 1 MiB."""
    import copy
    import tempfile
    import types
    sys.path.insert(0, str(ROOT / "hooks" / "ops"))
    import prompt_brief  # noqa: E402
    import prompt_gate  # noqa: E402

    prompts = scoring_corpus()[:400]
    variants = [v for v in OP_VARIANTS if v["name"] == only]
    cases = []
    with tempfile.TemporaryDirectory() as tmp:
        for variant in variants:
            cfg = config.DEFAULTS
            cfg = json.loads(json.dumps(cfg))
            for k, v in variant["patch"].items():
                cfg.setdefault(k, {}).update(v)
            for check in (True, False, None):
                state = {"turn": {"signals": {"check_shown": check}}}
                for text in prompts:
                    ctx = types.SimpleNamespace(
                        event="UserPromptSubmit", payload={"prompt": text, "cwd": tmp},
                        config=cfg, state=copy.deepcopy(state), pilot_executor=False, now=0.0)
                    gate = prompt_gate.run(ctx)
                    brief = prompt_brief.run(ctx) if check is None else None
                    cases.append({"variant": variant["name"], "check": check, "prompt": text,
                                  "gate": gate, "brief": brief})
    return HEADER + "\n" + ts_const("OP_CASES", cases, "ReadonlyArray<{ variant: string; check: boolean | null; prompt: string; gate: unknown; brief: unknown }>", compact=True)


